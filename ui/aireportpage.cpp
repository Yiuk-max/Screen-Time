WeeklyReport reportFromJson(const QJsonObject &obj)
{
    WeeklyReport report;
    report.reportId = obj.value(QStringLiteral("reportId")).toString();
    report.startDate = obj.value(QStringLiteral("startDate")).toString();
    report.endDate = obj.value(QStringLiteral("endDate")).toString();
    report.reportType = obj.value(QStringLiteral("reportType")).toString();
    report.content = obj.value(QStringLiteral("content")).toString();
    report.createdAt = obj.value(QStringLiteral("createdAt")).toString();
    report.serialNumber = obj.value(QStringLiteral("serialNumber")).toInt();
    report.isAutoGenerated = obj.value(QStringLiteral("isAutoGenerated")).toBool();

    if (report.reportId.isEmpty()) {
        report.reportId = QUuid::createUuid().toString(QUuid::WithoutBraces);
    }
    if (report.createdAt.isEmpty()) {
        report.createdAt = report.endDate + QStringLiteral(" 12:00:00");
    }
    if (report.serialNumber <= 0) {
        report.serialNumber = 1;
    }
    if (report.reportType.isEmpty()) {
        report.reportType = QStringLiteral("weekly");
    }
    return report;
}

QJsonObject reportToJson(const WeeklyReport &report)
{
    QJsonObject obj;
    obj[QStringLiteral("reportId")] = report.reportId;
    obj[QStringLiteral("startDate")] = report.startDate;
    obj[QStringLiteral("endDate")] = report.endDate;
    obj[QStringLiteral("reportType")] = report.reportType;
    obj[QStringLiteral("content")] = report.content;
    obj[QStringLiteral("createdAt")] = report.createdAt;
    obj[QStringLiteral("serialNumber")] = report.serialNumber;
    obj[QStringLiteral("isAutoGenerated")] = report.isAutoGenerated;
    return obj;
}

